// 同一 seed 下每轮遍历全部台词，不会靠随机抽样反复撞到同一句。
// cursor 由调用方按伙伴/上下文保存；last 可跨上下文避免连续说同一句。
export function pickPetDialogue(species,context,{cursor=0,last='',seed=0}={}){
 const id=Object.hasOwn(PET_DIALOGUE,species)?species:'libao';
 const key=Object.hasOwn(PET_DIALOGUE[id],context)?context:'idle';
 const pool=PET_DIALOGUE[id][key];
 let hash=2166136261;
 for(const ch of `${id}:${key}:${seed}`){hash^=ch.codePointAt(0);hash=Math.imul(hash,16777619)>>>0;}
 const order=pool.map((_,i)=>i);
 for(let i=order.length-1;i>0;i--){hash=(Math.imul(hash,1664525)+1013904223)>>>0;const j=hash%(i+1);[order[i],order[j]]=[order[j],order[i]];}
 let next=Number.isSafeInteger(cursor)&&cursor>=0?cursor:0;
 let text=pool[order[next++%order.length]];
 if(pool.length>1&&text===last)text=pool[order[next++%order.length]];
 return {text,cursor:next,context:key};
}
