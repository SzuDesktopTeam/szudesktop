// Parse public/fonts/fusion-pixel/fusion-pixel.css (copied verbatim from the app repo)
// into a typed list of {file, unicodeRange} so src/theme/fonts.ts can register every
// segment through the FontFace API and block rendering until all of them are loaded.
// Run again only if the font files are re-copied: node scripts/gen-font-faces.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const css = fs.readFileSync(path.join(root, 'public/fonts/fusion-pixel/fusion-pixel.css'), 'utf8');
const faces = [];
for (const block of css.split('@font-face').slice(1)) {
  const file = /url\(([^)]+\.woff2)\)/.exec(block)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim();
  if (!file || !range) throw new Error('Unexpected @font-face block: ' + block.slice(0, 200));
  if (!fs.existsSync(path.join(root, 'public/fonts/fusion-pixel', file))) throw new Error('Missing ' + file);
  faces.push({file, unicodeRange: range});
}
const out = `// Generated by scripts/gen-font-faces.mjs from public/fonts/fusion-pixel/fusion-pixel.css. Do not edit.
export const FUSION_PIXEL_FACES: ReadonlyArray<{file: string; unicodeRange: string}> = ${JSON.stringify(faces, null, 1)};
`;
fs.mkdirSync(path.join(root, 'src/theme'), {recursive: true});
fs.writeFileSync(path.join(root, 'src/theme/fusion-pixel-faces.ts'), out);
console.log(`wrote ${faces.length} faces`);
