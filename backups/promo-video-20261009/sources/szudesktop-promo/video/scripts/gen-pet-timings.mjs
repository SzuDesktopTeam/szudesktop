// Copy the app's per-frame pet animation timings (pet-animation.mjs PET_CLIPS) for the three
// original companions into src/lib/pet-timings.ts, so <PetSprite timing="native"> can replay
// an action at its authored rhythm. Pingu / Skipper / turtle are intentionally not exported.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const {PET_CLIPS} = await import('/Users/alakazan/workplace/szudesktop-promo-src/desktop/assets/garden/pet-animation.mjs');
const out = {};
for (const species of ['libao', 'chestnut', 'egret']) {
  out[species] = {};
  for (const [action, clip] of Object.entries(PET_CLIPS[species])) {
    out[species][action] = {loop: !!clip.loop, ms: clip.frames.map((f) => f.duration)};
  }
}
fs.writeFileSync(path.join(root, 'src/lib/pet-timings.ts'),
  `// Generated by scripts/gen-pet-timings.mjs from pet-animation.mjs PET_CLIPS. Do not edit.\n` +
  `export const PET_TIMINGS: Record<'libao' | 'chestnut' | 'egret', Record<string, {loop: boolean; ms: number[]}>> = ${JSON.stringify(out)};\n`);
console.log(Object.keys(out.libao).join(','), JSON.stringify(out.chestnut.signature), JSON.stringify(out.libao.idle));
